// BlockMark — 构建期打包：editor/*.js (ES modules) → editor.bundle.js (classic script)
// 原因：WKWebView 的 loadFileURL 会以 CORS 拦截 file:// 页面的 ES module 导入
// （与 headless Chrome 行为一致）。经典 <script> 串联无此问题：
// 单个 script 内顶层 function/const 天然共享作用域，import 名直接按裸名解析。
import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "EditorResources");
const files = ["editor/bridge.js", "editor/parser.js", "editor/inline.js", "editor/editor.js"];

let out = "// AUTO-GENERATED by tools/bundle.mjs — do not edit\n";
for (const f of files) {
  const code = readFileSync(join(src, f), "utf8")
    .replace(/^import\s+.*?;?\s*$/gm, "")            // 去 import 行（依赖顺序平铺）
    .replace(/^export\s+function\s+(\w+)/gm, "function $1") // export function → function
    .replace(/^export\s+const\s+(\w+)/gm, "const $1");      // export const → const
  out += `\n// ==== ${f} ====\n${code}\n`;
}
// 校验 1：classic script 语法可编译（抓残留 import/export、顶层重复声明）
new vm.Script(out, { filename: "editor.bundle.js" });
// 校验 2：不允许残留任何行首 import/export（转换规则未覆盖的导出形态）
if (/^[ \t]*(import|export)\b/m.test(out)) {
  throw new Error("bundle 产物残留 import/export 语句（转换规则缺口）");
}
writeFileSync(join(src, "editor.bundle.js"), out);

// 生成 app 用入口：经典 script 版 index.html
let html = readFileSync(join(src, "index.html"), "utf8");
const moduleTag = '<script type="module" src="editor/editor.js"></script>';
if (!html.includes(moduleTag)) {
  throw new Error("index.html 中未找到 module script 标签（bundle 注入将失效）");
}
html = html.replace(moduleTag, '<script src="editor.bundle.js" defer></script>');

// CodeMirror（存在则注入；依赖序：xml/javascript/css → 各语言 → markdown → htmlmixed）
const cmDir = join(src, "lib", "codemirror");
let cmTags = "";
try {
  const modeOrder = ["xml", "javascript", "css", "clike", "python", "shell", "go", "rust",
                     "yaml", "sql", "toml", "ruby", "php", "swift", "stex", "markdown", "htmlmixed"];
  const parts = modeOrder
    .map(m => `// ==== mode/${m} ====\n` + readFileSync(join(cmDir, `mode-${m}.js`), "utf8"))
    .join("\n");
  writeFileSync(join(cmDir, "modes.bundle.js"), parts);
  cmTags = `
<link rel="stylesheet" href="lib/codemirror/codemirror.min.css">
<script src="lib/codemirror/codemirror.min.js"></script>
<script src="lib/codemirror/runmode.min.js"></script>
<script src="lib/codemirror/modes.bundle.js"></script>`;
  html = html.replace("<script", cmTags + "\n<script");
} catch {
  console.log("CodeMirror not present, skipping CM tags");
}

// KaTeX + mermaid（存在则注入）
try {
  const extraTags = `
<link rel="stylesheet" href="lib/katex/katex.min.css">
<script src="lib/katex/katex.min.js"></script>
<script src="lib/mermaid.min.js"></script>`;
  readFileSync(join(src, "lib", "katex", "katex.min.js"));
  readFileSync(join(src, "lib", "mermaid.min.js"));
  html = html.replace("<script", extraTags + "\n<script");
} catch {
  console.log("KaTeX/mermaid not present, skipping");
}
writeFileSync(join(src, "index.bundle.html"), html);
console.log("bundled: editor.bundle.js + index.bundle.html" + (cmTags ? " + CodeMirror" : ""));
